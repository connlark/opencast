//! Swift sources the policy generator writes into the app's analysis package:
//! the baked bundle the build ships with and the signed loader test fixtures.
//! Both embed the exact bytes as raw string literals, so the package needs no
//! resource bundle and the bytes compare equal to the generator's output.

use crate::{
    analysis_policy::{sign_policy_bytes, AnalysisPolicyBundle},
    manifest_signature::public_key_hex_from_signing_key_hex,
};
use sha2::{Digest, Sha256};

/// Key id of the throwaway test key the loader fixtures are signed with.
pub const TEST_KEY_ID: &str = "opencast-analysis-policy-test";
const TEST_SEED_LABEL: &[u8] = b"opencast analysis policy test key; never a production key";

/// The test signing seed: SHA-256 of a public label, so anyone can regenerate
/// the fixtures and nothing secret is involved.
pub fn test_signing_seed_hex() -> String {
    hex::encode(Sha256::digest(TEST_SEED_LABEL))
}

/// The baked-copy Swift source for `bundle_bytes`.
///
/// # Errors
///
/// Returns an error when the bytes cannot be embedded in a raw literal.
pub fn baked_source(bundle_bytes: &[u8], bundle_version: u32) -> Result<String, String> {
    let json = raw_literal(bundle_bytes)?;
    let digest = hex::encode(Sha256::digest(bundle_bytes));
    Ok(format!(
        "// Generated by `generate_policy` (Server/ModelGatewayWorker) from the analysis\n\
         // workers' constants. Do not edit; regenerate, and the generator's tests\n\
         // check these bytes against the served bundle.\n\
         \n\
         /// The analysis policy bundle this build ships with, used until a newer\n\
         /// signed bundle is downloaded and accepted.\n\
         enum BakedAnalysisPolicy {{\n\
         \x20   static let bundleVersion = {bundle_version}\n\
         \x20   /// SHA-256 of `json`'s UTF-8 bytes.\n\
         \x20   static let sha256 = \"{digest}\"\n\
         \x20   static let json = {json}\n\
         }}\n"
    ))
}

/// One signed loader fixture.
pub struct TestFixture {
    pub name: &'static str,
    pub summary: &'static str,
    pub bundle: Vec<u8>,
    pub signature: Vec<u8>,
}

/// The loader fixtures, derived from `base` and signed with the test key:
/// two acceptable versions above the base, a bad signature, a widened window
/// and a bundle that needs a far newer app build.
///
/// # Errors
///
/// Returns an error when serialization or signing fails.
pub fn test_fixtures(base: &AnalysisPolicyBundle) -> Result<Vec<TestFixture>, String> {
    let seed = test_signing_seed_hex();
    let sign = |bundle: &AnalysisPolicyBundle| -> Result<(Vec<u8>, Vec<u8>), String> {
        let bytes = serde_json::to_vec(bundle).map_err(|error| error.to_string())?;
        let signature = sign_policy_bytes(&bytes, TEST_KEY_ID, &seed)?;
        let envelope = serde_json::to_vec_pretty(&signature).map_err(|error| error.to_string())?;
        Ok((bytes, envelope))
    };

    let mut good = base.clone();
    good.bundle_version = base.bundle_version + 1;
    let mut next = base.clone();
    next.bundle_version = base.bundle_version + 2;
    let mut widened = good.clone();
    widened.features.ad_detection.window.segments += 1;
    let mut future = good.clone();
    future.min_app_build = 1_000_000;

    let (good_bytes, good_signature) = sign(&good)?;
    let (next_bytes, next_signature) = sign(&next)?;
    let (widened_bytes, widened_signature) = sign(&widened)?;
    let (future_bytes, future_signature) = sign(&future)?;
    let bad_signature = {
        let mut envelope = sign_policy_bytes(&good_bytes, TEST_KEY_ID, &seed)?;
        let flipped = if envelope.signature.ends_with('0') {
            '1'
        } else {
            '0'
        };
        envelope.signature.pop();
        envelope.signature.push(flipped);
        serde_json::to_vec_pretty(&envelope).map_err(|error| error.to_string())?
    };

    Ok(vec![
        TestFixture {
            name: "good",
            summary: "The base bundle one version up, correctly signed.",
            bundle: good_bytes.clone(),
            signature: good_signature,
        },
        TestFixture {
            name: "next",
            summary: "The base bundle two versions up, correctly signed.",
            bundle: next_bytes,
            signature: next_signature,
        },
        TestFixture {
            name: "badSignature",
            summary: "`good`'s bytes with one signature nibble changed.",
            bundle: good_bytes,
            signature: bad_signature,
        },
        TestFixture {
            name: "widenedWindow",
            summary:
                "`good` with the ad window one segment wider than qualified, correctly signed.",
            bundle: widened_bytes,
            signature: widened_signature,
        },
        TestFixture {
            name: "futureMinAppBuild",
            summary: "`good` requiring app build 1,000,000, correctly signed.",
            bundle: future_bytes,
            signature: future_signature,
        },
    ])
}

/// The test-fixture Swift source.
///
/// # Errors
///
/// Returns an error when a fixture cannot be embedded in a raw literal.
pub fn fixtures_source(fixtures: &[TestFixture]) -> Result<String, String> {
    let public_key = public_key_hex_from_signing_key_hex(&test_signing_seed_hex())?;
    let mut source = format!(
        "// Generated by `generate_policy` (Server/ModelGatewayWorker). Do not edit.\n\
         // Signed with a throwaway test key derived from a public label, never the\n\
         // production key.\n\
         \n\
         struct AnalysisPolicyFixture {{\n\
         \x20   let bundle: String\n\
         \x20   let signature: String\n\
         }}\n\
         \n\
         enum AnalysisPolicyTestFixtures {{\n\
         \x20   static let publicKeyHex = \"{public_key}\"\n\
         \x20   static let keyID = \"{TEST_KEY_ID}\"\n"
    );
    for fixture in fixtures {
        source.push_str(&format!(
            "\n\x20   /// {}\n\x20   static let {} = AnalysisPolicyFixture(\n\x20       bundle: {},\n\x20       signature: {}\n\x20   )\n",
            fixture.summary,
            fixture.name,
            raw_literal(&fixture.bundle)?,
            raw_literal(&fixture.signature)?
        ));
    }
    source.push_str("}\n");
    Ok(source)
}

/// A Swift multi-line raw string literal whose value is exactly `bytes`.
/// The closing delimiter sits at column zero, so no indentation is stripped.
fn raw_literal(bytes: &[u8]) -> Result<String, String> {
    let text = std::str::from_utf8(bytes).map_err(|error| error.to_string())?;
    if text.contains("\"\"\"##") || text.contains("\\##") || text.contains('\r') {
        return Err("bytes cannot be embedded in a ##\"\"\" raw literal".to_string());
    }
    Ok(format!("##\"\"\"\n{text}\n\"\"\"##"))
}
